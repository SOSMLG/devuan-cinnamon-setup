#!/usr/bin/env bash
# =======================================================
# 08 Firefox — install & harden Firefox ESR (Betterfox)
# -------------------------------------------------------
# Adapted from harden_firefox.sh (Butterbian) for Devuan Cinnamon Setup.
# Concept: tonybanters/tonarchy.
#
# Deterministic run (no menu): ensures firefox-esr is installed, fetches a
# pinned Betterfox user.js (+ a few Linux-targeted additions) into a cache,
# creates/uses a hardened profile, pushes privacy/de-branding policies to
# the system distribution dir, replaces the .desktop, and drops a wrapper
# in ~/.local/bin that re-applies the latest user.js on every launch.
# If a separate 'firefox' (latest) install also exists, it is hardened too.
# =======================================================
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/../lib/common.sh"

require_not_root
log_head "08 Firefox"

# Pinned Betterfox tag — bump here when reviewing upstream changes.
# Tags published at https://github.com/yokoffing/Betterfox/tags
BETTERFOX_TAG="${BETTERFOX_TAG:-150.0}"
BETTERFOX_URL="https://raw.githubusercontent.com/yokoffing/Betterfox/${BETTERFOX_TAG}/user.js"

MOZ_DIR="$HOME/.mozilla/firefox"
USERJS_CACHE_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/butterscripts/firefox"
USERJS_CACHE="$USERJS_CACHE_DIR/user.js"

if [ ! -f "$SCRIPT_DIR/policies.json" ]; then
    log_err "policies.json not found in $SCRIPT_DIR."
    exit 1
fi

# ---------------------------------------------------------------------------
# 1. Install firefox-esr if it isn't present yet — this project targets ESR.
# ---------------------------------------------------------------------------
if is_installed firefox-esr; then
    log_ok "firefox-esr already installed."
else
    log_info "Installing firefox-esr..."
    install_pkgs "Download tools (curl)" curl ca-certificates
    apt_update
    sudo apt-get install -y firefox-esr && log_ok "firefox-esr installed." \
        || { log_err "Failed to install firefox-esr."; exit 1; }
fi

# ---------------------------------------------------------------------------
# 2. Fetch pinned Betterfox + append hardening additions -> cached user.js
# ---------------------------------------------------------------------------
mkdir -p "$USERJS_CACHE_DIR"
log_info "Fetching Betterfox ${BETTERFOX_TAG}..."
if ! curl -fL "$BETTERFOX_URL" -o "$USERJS_CACHE.upstream"; then
    log_err "Failed to fetch Betterfox ${BETTERFOX_TAG} from $BETTERFOX_URL"
    rm -f "$USERJS_CACHE.upstream"
    exit 1
fi
{
    cat << HEADER
// Firefox hardening — Betterfox ${BETTERFOX_TAG} + additions
// Generated by scripts/08-firefox.sh
// Re-run that script to refresh from upstream.

HEADER
    cat "$USERJS_CACHE.upstream"
    cat << 'ADDITIONS'

// ============================================================================
// ADDITIONS — Linux-targeted, intentional, minimal
// ============================================================================

// Saved passwords still work; require click to fill.
// Defends against autofill-into-injected-form attacks.
user_pref("signon.autofillForms", false);

// Don't let geoclue answer geolocation queries — defense beyond
// Betterfox's permissions.default.geo: 2.
user_pref("geo.provider.use_geoclue", false);

// Better default PDF zoom — fits the page width.
user_pref("pdfjs.defaultZoomValue", "page-width");

// Dismiss the Firefox View tour. Completes policies.json's
// SkipOnboarding / WhatsNew / MoreFromMozilla stance.
user_pref("browser.firefox-view.feature-tour", "{\"screen\":\"\",\"complete\":true}");
ADDITIONS
} > "$USERJS_CACHE"
rm -f "$USERJS_CACHE.upstream"
log_ok "user.js generated at $USERJS_CACHE."

# ---------------------------------------------------------------------------
# 3. Hardened profile + policies + .desktop + wrapper for one browser
# ---------------------------------------------------------------------------
BIN_DIR="$HOME/.local/bin"
mkdir -p "$BIN_DIR"

harden_firefox() {
    local browser_name="$1" exec_name="$2" distribution_dir="$3" desktop_file="$4" icon_name="$5" profile_name="$6"
    local profile_dir="$MOZ_DIR/$profile_name"

    echo ""
    log_info "Hardening $browser_name ($profile_name)"

    # Profile base
    if [ ! -d "$MOZ_DIR" ]; then
        mkdir -p "$profile_dir"
        cat > "$MOZ_DIR/profiles.ini" << PROF_EOF
[General]
StartWithLastProfile=1
Version=2

[Profile0]
Name=$profile_name
IsRelative=1
Path=$profile_name
Default=1
PROF_EOF
        log_ok "Profile created at $profile_dir."
    else
        local found=0
        for dir in "$MOZ_DIR"/*."$profile_name"; do
            if [ -d "$dir" ]; then
                profile_dir="$dir"; found=1; break
            fi
        done
        [ "$found" -eq 0 ] && mkdir -p "$profile_dir"
    fi
    cp "$USERJS_CACHE" "$profile_dir/user.js"
    log_ok "user.js installed to $profile_dir."

    # Policies (system distribution dir)
    if [ ! -d "$distribution_dir" ]; then
        sudo mkdir -p "$distribution_dir"
    fi
    if sudo cp "$SCRIPT_DIR/policies.json" "$distribution_dir/policies.json"; then
        log_ok "Policies installed to $distribution_dir."
    else
        log_err "Failed to install policies.json."
        return 1
    fi

    # .desktop — name/icon match the hardened build
    sudo tee "/usr/share/applications/$desktop_file" > /dev/null << EOF
[Desktop Entry]
Name=$browser_name
GenericName=Web Browser
Exec=$exec_name %u
Terminal=false
Type=Application
Icon=$icon_name
Categories=Network;WebBrowser;
MimeType=text/html;text/xml;application/xhtml+xml;application/vnd.mozilla.xul+xml;text/mml;x-scheme-handler/http;x-scheme-handler/https;
StartupNotify=true
StartupWMClass=$exec_name
EOF
    log_ok "System desktop file updated: /usr/share/applications/$desktop_file"

    # Wrapper in ~/.local/bin shadowing the system binary, re-applying
    # user.js from cache on every launch.
    cat > "$BIN_DIR/$exec_name" << WRAPPER_EOF
#!/bin/sh
MOZ_DIR="\$HOME/.mozilla/firefox"
USERJS="\${XDG_DATA_HOME:-\$HOME/.local/share}/butterscripts/firefox/user.js"

if [ -f "\$USERJS" ]; then
    for dir in "\$MOZ_DIR"/*.$profile_name; do
        if [ -d "\$dir" ]; then
            cp "\$USERJS" "\$dir/user.js" 2>/dev/null
            break
        fi
    done
fi

exec /usr/bin/$exec_name "\$@"
WRAPPER_EOF
    chmod +x "$BIN_DIR/$exec_name"
    log_ok "Wrapper installed: $BIN_DIR/$exec_name"
    log_ok "$browser_name hardening complete!"
}

harden_firefox "Firefox ESR" "firefox-esr" "/usr/lib/firefox-esr/distribution" "firefox-esr.desktop" "firefox-esr" "default-esr"
is_installed firefox && harden_firefox "Firefox" "firefox" "/usr/lib/firefox/distribution" "firefox.desktop" "firefox" "default-release"

echo -e "${GREEN}08 Firefox complete.${NC}"
log_warn "If ~/.local/bin isn't on your PATH, add 'export PATH=\$HOME/.local/bin:\$PATH' to your shell rc."